# 1. Re-extract to ensure folders exist
zip_name = 'dataset.zip'
target_base = '/content/pcos_data'

if os.path.exists(zip_name):
    print(f'Extracting {zip_name}...')
    if os.path.exists(target_base): shutil.rmtree(target_base)
    with zipfile.ZipFile(zip_name, 'r') as zip_ref:
        zip_ref.extractall(target_base)

# 2. Locate train/test even if nested
found_train = None
found_test = None
for root, dirs, files in os.walk(target_base):
    if 'train' in dirs:
        found_train = os.path.join(root, 'train')
    if 'test' in dirs:
        found_test = os.path.join(root, 'test')

if found_train and found_test:
    train_dir, test_dir = found_train, found_test
    print(f'Dataset ready at: {train_dir}')

    def clean_dataset(directory):
        removed = 0
        for root, _, files in os.walk(directory):
            for file in files:
                file_path = os.path.join(root, file)
                if file.startswith('.'):
                    os.remove(file_path)
                    removed += 1
                    continue
                try:
                    with Image.open(file_path) as img: img.verify()
                except:
                    os.remove(file_path)
                    removed += 1
        return removed

    print('Cleaning images...')
    clean_dataset(train_dir)
    clean_dataset(test_dir)

    # 3. Setup generators and train
    # Using BATCH_SIZE=32 for more stable training if memory allows, otherwise keeping at 2 as initialized
    train_generator = train_datagen.flow_from_directory(train_dir, target_size=(224, 224), batch_size=2, class_mode='binary')
    validation_generator = test_datagen.flow_from_directory(test_dir, target_size=(224, 224), batch_size=2, class_mode='binary')

    early_stop = EarlyStopping(monitor='val_loss', patience=3, restore_best_weights=True)
    print('\nStarting training...')
    # CRITICAL: Capturing the return value in HISTORY
    HISTORY = model.fit(train_generator, epochs=10, validation_data=validation_generator, callbacks=[early_stop])
    print('\nTraining complete. History saved.')
