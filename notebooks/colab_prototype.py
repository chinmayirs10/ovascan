"""## Understanding the Data Pipeline

### Subtask:
Configure image data generators for normalization and augmentation to prepare the images for the CNN.

**Reasoning**:
I will initialize the ImageDataGenerators with normalization and basic augmentation to prepare the dataset for training.
"""

from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Set image dimensions
IMG_HEIGHT = 224
IMG_WIDTH = 224
BATCH_SIZE = 2

# Initialize the Training Data Generator with augmentation and normalization
train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=20,
    width_shift_range=0.2,
    height_shift_range=0.2,
    horizontal_flip=True,
    fill_mode='nearest'
)

# Initialize the Test Data Generator with only normalization
test_datagen = ImageDataGenerator(rescale=1./255)

# Create data flow
train_generator = train_datagen.flow_from_directory(
    train_dir,
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='binary'
)

validation_generator = test_datagen.flow_from_directory(
    test_dir,
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='binary'
)

print('Data pipeline configured. Images will be normalized to [0, 1] range.')

"""## CNN Model Architecture

### Subtask:
Design a Convolutional Neural Network (CNN) tailored for binary classification of ultrasound images.
"""

model = models.Sequential([
    # First Convolutional block
    layers.Conv2D(32, (3, 3), activation='relu', input_shape=(IMG_HEIGHT, IMG_WIDTH, 3)),
    layers.MaxPooling2D((2, 2)),

    # Second Convolutional block
    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Third Convolutional block
    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Flatten and Dense layers
    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5), # Helps prevent overfitting
    layers.Dense(1, activation='sigmoid') # Binary output: Infected vs Not-Infected
])

model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

model.summary()

"""## Model Training

### Subtask:
Train the CNN model on the ultrasound dataset and monitor the accuracy and loss.
"""

import zipfile
