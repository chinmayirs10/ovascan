"""Audit the raw dataset for leakage and write a leakage-free split.

Usage:
    python scripts/audit_dataset.py --data dataset/data

Outputs:
    reports/data_audit.md    human-readable findings
    reports/data_audit.json  the same numbers, machine-readable
    reports/families.png     sample images per detected family
    splits/split.csv         path,label,family,split  (used by train.py)
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import torch
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pcos_screen.data import (  # noqa: E402
    LABEL_NAMES, deduplicate, group_into_families, group_split, scan_dataset, write_split_csv,
)
from pcos_screen.model import build_feature_extractor, eval_transform  # noqa: E402


@torch.no_grad()
def embed(paths: list[Path], batch: int = 64) -> np.ndarray:
    net = build_feature_extractor()
    out = []
    for i in range(0, len(paths), batch):
        imgs = [Image.open(p).convert("RGB") for p in paths[i:i + batch]]
        x = torch.stack([eval_transform(im) for im in imgs])
        # average with horizontal flip so mirrored augmentations land together
        e = (net(x) + net(torch.flip(x, dims=[3]))) / 2
        out.append(torch.nn.functional.normalize(e, dim=1).numpy())
        print(f"  embedded {min(i + batch, len(paths))}/{len(paths)}", end="\r")
    print()
    return np.concatenate(out)


def save_family_grid(paths, families, labels, out: Path, n_fams=8, per_fam=6):
    tile = 96
    rows = []
    for label in (1, 0):
        fams = [f for f, _ in Counter(families[labels == label]).most_common(n_fams // 2)]
        for f in fams:
            idx = np.where(families == f)[0][:per_fam]
            rows.append([Image.open(paths[i]).convert("RGB").resize((tile, tile)) for i in idx])
    grid = Image.new("RGB", (tile * per_fam, tile * len(rows)), "white")
    for r, row in enumerate(rows):
        for c, im in enumerate(row):
            grid.paste(im, (c * tile, r * tile))
    grid.save(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=Path("dataset/data"))
    ap.add_argument("--threshold", type=float, default=0.15,
                    help="cosine distance below which images count as the same family")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    root = Path(__file__).resolve().parents[1]
    reports = root / "reports"
    reports.mkdir(exist_ok=True)

    print("Scanning", args.data)
    records = scan_dataset(args.data)
    original_counts = Counter((r.source_split, LABEL_NAMES[r.label]) for r in records)
    unique, dedup_stats = deduplicate(records)
    print("Exact duplicates:", dedup_stats)

    paths = [r.path for r in unique]
    labels = np.array([r.label for r in unique])
    print("Embedding images for near-duplicate detection...")
    emb = embed(paths)
    families = group_into_families(emb, labels, threshold=args.threshold)
    split = group_split(families, labels, seed=args.seed)

    fam_sizes = Counter(families)
    per_class_fams = {LABEL_NAMES[l]: int(len(np.unique(families[labels == l]))) for l in (1, 0)}
    split_counts = {s: {LABEL_NAMES[l]: int(((split == s) & (labels == l)).sum()) for l in (1, 0)}
                    for s in ("train", "val", "test")}
    split_fams = {s: int(len(np.unique(families[split == s]))) for s in ("train", "val", "test")}

    summary = {
        "original_folder_counts": {f"{s}/{c}": n for (s, c), n in sorted(original_counts.items())},
        "exact_duplicates": dedup_stats,
        "family_threshold_cosine": args.threshold,
        "families_per_class": per_class_fams,
        "largest_family_sizes": sorted(fam_sizes.values(), reverse=True)[:10],
        "group_split_images": split_counts,
        "group_split_families": split_fams,
    }
    (reports / "data_audit.json").write_text(json.dumps(summary, indent=2))

    rows = [{"path": p.relative_to(root).as_posix() if p.is_absolute() else p.as_posix(),
             "label": int(l), "family": int(f), "split": s}
            for p, l, f, s in zip(paths, labels, families, split)]
    write_split_csv(root / "splits" / "split.csv", rows)
    save_family_grid(paths, families, labels, reports / "families.png")

    md = [
        "# Dataset audit",
        "",
        "Generated by `scripts/audit_dataset.py`.",
        "",
        "## 1. Exact duplicates",
        "",
        f"- Files on disk: **{dedup_stats['files_total']}**",
        f"- Unique file contents: **{dedup_stats['unique_contents']}**",
        f"- Contents present in *both* `train/` and `test/`: **{dedup_stats['duplicated_across_splits']}**",
        f"- Same image with conflicting labels (dropped): {dedup_stats['label_conflicts_dropped']}",
        "",
        "The provided test folder is essentially a copy of the training folder, so any "
        "accuracy measured on it shows memorisation, not generalisation.",
        "",
        "## 2. Near-duplicates (augmentation families)",
        "",
        f"Images were embedded with an ImageNet MobileNetV3 and clustered "
        f"(cosine distance < {args.threshold}).",
        "",
        f"- Families per class: {per_class_fams}",
        f"- Largest family sizes: {summary['largest_family_sizes']}",
        "",
        "![families](families.png)",
        "",
        "Each row above is one detected family. Many images are flips/zooms of the same scan.",
        "",
        "## 3. Leakage-free split",
        "",
        "Whole families are assigned to one split only (`splits/split.csv`).",
        "",
        "| split | pcos_like | normal | families |",
        "|---|---|---|---|",
        *[f"| {s} | {split_counts[s]['pcos_like']} | {split_counts[s]['normal']} | {split_fams[s]} |"
          for s in ("train", "val", "test")],
        "",
        "## 4. Other observations",
        "",
        "- Many images in the `notinfected` class show the uterus rather than an ovary. "
        "A model can then learn *which organ is visible* instead of *what the ovary looks like* "
        "(shortcut learning). This must be fixed with better data before any result means something clinically.",
        "- Images vary in size and some contain on-screen annotations or UI text from the scanner.",
    ]
    (reports / "data_audit.md").write_text("\n".join(md), encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
